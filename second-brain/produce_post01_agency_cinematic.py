async def synthesize_voiceover(output_mp3: Path) -> float:
    import edge_tts

    communicate = edge_tts.Communicate(VOICEOVER_SCRIPT, voice="vi-VN-HoaiMyNeural", rate="+2%")
    await communicate.save(str(output_mp3))
    probe = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "default=noprint_wrappers=1:nokey=1", str(output_mp3)],
        capture_output=True,
        text=True,
        check=True,
    )
    return float(probe.stdout.strip() or "22.0")


def render_cinematic_reel_mp4(vertical_plates: list[Path], voice_mp3: Path, duration_sec: float, output_mp4: Path) -> None:
    total_dur = max(20.0, round(duration_sec + 1.5, 2))
    seg_dur = round(total_sec_per_scene := (total_dur / 4.0) + 0.6, 2)
    frames_per_seg = int(seg_dur * 30)

    # Render 4 smooth optical camera movement segments with 35mm film grain
    seg_files: list[Path] = []
    for i, plate in enumerate(vertical_plates):
        seg_out = MEDIA_VAULT_DIR / f"tmp_cin_seg_{i}.mp4"
        if i % 2 == 0:
            zp = f"zoompan=z='min(zoom+0.0005,1.08)':d={frames_per_seg}:x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':s=1080x1920:fps=30"
        else:
            zp = f"zoompan=z='1.08-0.0004*on':d={frames_per_seg}:x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':s=1080x1920:fps=30"
        vf = f"{zp},noise=alls=3:allf=t+u,format=yuv420p"
        subprocess.run(
            [
                "ffmpeg",
                "-y",
                "-loop",
                "1",
                "-i",
                str(plate),
                "-t",
                str(seg_dur),
                "-vf",
                vf,
                "-c:v",
                "libx264",
                "-preset",
                "fast",
                "-crf",
                "18",
                str(seg_out),
            ],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        seg_files.append(seg_out)

    # Crossfade the 4 segments and mix warm ambient harmonic pad + voiceover
    o1 = round(seg_dur - 0.5, 2)
    o2 = round(2 * seg_dur - 1.0, 2)
    o3 = round(3 * seg_dur - 1.5, 2)
    filter_complex = (
        f"[0:v][1:v]xfade=transition=fade:duration=0.5:offset={o1}[v01];"
        f"[v01][2:v]xfade=transition=fade:duration=0.5:offset={o2}[v02];"
        f"[v02][3:v]xfade=transition=fade:duration=0.5:offset={o3}[vout];"
        f"aevalsrc='0.018*sin(2*PI*220*t)+0.014*sin(2*PI*277.18*t)+0.012*sin(2*PI*329.63*t)+0.009*sin(2*PI*440*t)':s=44100:d={total_dur}[bgm];"
        f"[4:a]volume=1.35[vo];"
        f"[bgm][vo]amix=inputs=2:duration=first:dropout_transition=2[aout]"
    )
    subprocess.run(
        [
            "ffmpeg",
            "-y",
            "-i",
            str(seg_files[0]),
            "-i",
            str(seg_files[1]),
            "-i",
            str(seg_files[2]),
            "-i",
            str(seg_files[3]),
            "-i",
            str(voice_mp3),
            "-filter_complex",
            filter_complex,
            "-map",
            "[vout]",
            "-map",
            "[aout]",
            "-c:v",
            "libx264",
            "-preset",
            "fast",
            "-crf",
            "18",
            "-c:a",
            "aac",
            "-b:a",
            "192k",
            "-shortest",
            str(output_mp4),
        ],
        check=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    for sf in seg_files:
        sf.unlink(missing_ok=True)


